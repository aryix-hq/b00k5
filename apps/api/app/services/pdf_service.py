import io
import hashlib
from datetime import datetime
from typing import Dict, Any, Optional

class PDFService:
    @staticmethod
    def generate_simple_invoice_pdf(invoice_data: Dict[str, Any]) -> bytes:
        """
        Generates a standard PDF document byte stream for a GST Tax Invoice.
        For self-contained portability, writes a compliant PDF structure.
        """
        buf = io.BytesIO()
        inv_no = invoice_data.get("invoice_number", "INV-001")
        total = invoice_data.get("grand_total", "0.00")
        subtotal = invoice_data.get("subtotal", "0.00")
        gst_total = float(invoice_data.get("cgst_total", 0)) + float(invoice_data.get("sgst_total", 0)) + float(invoice_data.get("igst_total", 0))
        issue_date = str(invoice_data.get("issue_date", datetime.utcnow().strftime("%Y-%m-%d")))
        contact_name = invoice_data.get("contact_name", "Valued Customer")
        place_of_supply = invoice_data.get("place_of_supply", "29")

        # Standard minimal PDF content stream
        content = f"""%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>
endobj
4 0 obj
<< /Length 400 >>
stream
BT
/F1 20 Tf
50 720 Td
(TAX INVOICE) Tj
/F1 12 Tf
0 -30 Td
(Invoice Number: {inv_no}) Tj
0 -20 Td
(Date: {issue_date}) Tj
0 -20 Td
(Billed To: {contact_name}) Tj
0 -20 Td
(Place of Supply: {place_of_supply}) Tj
0 -40 Td
(Subtotal: INR {subtotal}) Tj
0 -20 Td
(GST Total: INR {gst_total:.2f}) Tj
0 -20 Td
(Grand Total: INR {total}) Tj
0 -40 Td
(Generated by b00k5 - Local-First Financial OS for Indian Startups) Tj
ET
endstream
endobj
5 0 obj
<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>
endobj
xref
0 6
0000000000 65535 f 
0000000009 00000 n 
0000000058 00000 n 
0000000115 00000 n 
0000000244 00000 n 
0000000700 00000 n 
trailer
<< /Size 6 /Root 1 0 R >>
startxref
775
%%EOF
"""
        return content.encode("utf-8")

    @staticmethod
    def compute_sha256(data: bytes) -> str:
        return hashlib.sha256(data).hexdigest()
