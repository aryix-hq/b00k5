import io
import hashlib
from datetime import datetime
from typing import Dict, Any, Optional

class PDFService:
    @staticmethod
    def generate_simple_invoice_pdf(invoice_data: Dict[str, Any]) -> bytes:
        """
        Generates a standard PDF document byte stream for a GST Tax Invoice
        with exact ISO 32000-1 xref byte offsets.
        """
        from app.services.document_assembly import DocumentAssemblyService

        inv_no = invoice_data.get("invoice_number", "INV-001")
        total = invoice_data.get("grand_total", "0.00")
        subtotal = invoice_data.get("subtotal", "0.00")
        gst_total = float(invoice_data.get("cgst_total", 0)) + float(invoice_data.get("sgst_total", 0)) + float(invoice_data.get("igst_total", 0))
        issue_date = str(invoice_data.get("issue_date", datetime.utcnow().strftime("%Y-%m-%d")))
        contact_name = invoice_data.get("contact_name", "Valued Customer")
        place_of_supply = invoice_data.get("place_of_supply", "29")

        lines = [
            "================================================================================",
            f"Invoice Number  : {inv_no}",
            f"Issue Date      : {issue_date}",
            f"Billed To       : {contact_name}",
            f"Place of Supply : {place_of_supply}",
            "--------------------------------------------------------------------------------",
            f"Taxable Subtotal: INR {subtotal}",
            f"GST Total       : INR {gst_total:.2f}",
            f"Grand Total     : INR {total}",
            "================================================================================",
            "Generated by b00k5 - Local-First Financial OS for Indian Startups"
        ]
        return DocumentAssemblyService._create_pdf_document(f"TAX INVOICE - {inv_no}", lines)

    @staticmethod
    def compute_sha256(data: bytes) -> str:
        return hashlib.sha256(data).hexdigest()

